#!/usr/bin/env python3
"""Acceptance against a disposable Nexus using native gem/Bundler and DNF/RPM."""
import argparse
import base64
import io
import gzip
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tarfile
import tempfile
import time
import urllib.error
import urllib.request
import xml.etree.ElementTree as ET
from native_test_support import NexusTest

ROOT=Path(__file__).resolve().parents[1]
NETWORK="nexus-ha_default"
CLIENT="nexus-ha-ruby-yum-client"
FIXTURE="nexus-ha-ruby-yum-upstream"


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--url",default="http://127.0.0.1:18125")
    parser.add_argument("--container",default="nexus-ha-ruby-yum")
    parser.add_argument("--keep-repositories",action="store_true",help="Keep only task-created repositories for inspection after a failed test")
    args=parser.parse_args()
    if not args.container.startswith("nexus-ha-"):raise ValueError("Use an isolated test-suite Nexus fixture")
    test=NexusTest(args.url,args.container)
    fixture=FIXTURE+"-"+test.suffix
    with tempfile.TemporaryDirectory(prefix="nexus-ruby-yum-")as directory:
        work=Path(directory);work.chmod(0o700)
        auth_file=work/"client.env";auth_file.write_text("GEM_HOST_API_KEY=Basic "+test.basic+"\n");auth_file.chmod(0o600)
        def client(*command):
            return test.run(["docker","run","--rm","--network",NETWORK,"--env-file",str(auth_file),"--mount",f"type=bind,src={work},dst=/work",CLIENT,*command])
        def create(format,kind,label,members=None,remote=None):
            saved=test.suffix;test.suffix=saved+"-"+label
            try:return test.repository(format,kind,members=members,remote=remote)
            finally:test.suffix=saved
        def expect_rejected(path,method,body,headers=None):
            values={"Authorization":"Basic "+test.basic,"Content-Type":"application/octet-stream"};values.update(headers or {})
            try:
                urllib.request.urlopen(urllib.request.Request(args.url+path,data=body,method=method,headers=values),timeout=30)
                raise AssertionError("Invalid package was accepted: "+path)
            except urllib.error.HTTPError as error:
                if error.code!=400:raise AssertionError(f"Invalid package must return HTTP 400; got {error.code}")from None
        _,raw=test.request("/service/rest/v1/security/ssrf-protection")
        original=json.loads(raw);changed=dict(original);changed["allowedDomains"]=list(original.get("allowedDomains",[]))+[fixture,args.container]
        fixture_started=False
        try:
            # Build real gems with a dependency split between two hosted members.
            child="nexus-child-"+test.suffix;app="nexus-app-"+test.suffix
            for name,dependency in [(child,None),(app,child)]:
                folder=work/name;folder.mkdir();(folder/"lib").mkdir();(folder/"lib"/(name+".rb")).write_text("NEXUS_NATIVE_PROOF='ok'\n")
                dependency_line=f"s.add_dependency '{dependency}', '= 1.0.0'" if dependency else ""
                (folder/(name+".gemspec")).write_text(f"Gem::Specification.new do |s|\ns.name='{name}'\ns.version='1.0.0'\ns.summary='Nexus protocol acceptance'\ns.authors=['Nexus test']\ns.files=Dir['lib/*.rb']\ns.license='MIT'\n{dependency_line}\nend\n")
                client("sh","-ec",f"cd /work/{name}; gem build {name}.gemspec")
            ruby_a=create("rubygems","hosted","a");ruby_b=create("rubygems","hosted","b")
            api_a=f"http://{args.container}:8081/repository/{ruby_a}"
            api_b=f"http://{args.container}:8081/repository/{ruby_b}"
            client("gem","push",f"/work/{child}/{child}-1.0.0.gem","--host",api_a)
            client("gem","push",f"/work/{app}/{app}-1.0.0.gem","--host",api_b)
            expect_rejected(f"/repository/{ruby_a}/api/v1/gems","POST",b"not-a-gem")
            gem_bytes=(work/child/f"{child}-1.0.0.gem").read_bytes()
            expect_rejected(f"/repository/{ruby_a}/api/v1/gems","POST",gem_bytes,{"X-Checksum-Sha256":"0"*64})
            # Keep the original checksum manifest while changing compressed data.
            corrupt=io.BytesIO()
            with tarfile.open(fileobj=io.BytesIO(gem_bytes),mode="r:")as archive,tarfile.open(fileobj=corrupt,mode="w:")as output:
                for entry in archive:
                    content=archive.extractfile(entry).read()
                    if entry.name=="data.tar.gz":content=content[:-1]+bytes([content[-1]^1])
                    entry.size=len(content);output.addfile(entry,io.BytesIO(content))
            expect_rejected(f"/repository/{ruby_a}/api/v1/gems","POST",corrupt.getvalue())
            # The index generated by real Ruby is an independent proxy fixture.
            upstream=work/"upstream";gemdir=upstream/"ruby/gems";gemdir.mkdir(parents=True)
            import shutil
            for name in (child,app):shutil.copyfile(work/name/f"{name}-1.0.0.gem",gemdir/f"{name}-1.0.0.gem")
            client("gem","generate_index","--directory","/work/upstream/ruby")
            subprocess.run(["docker","run","-d","--name",fixture,"--network",NETWORK,"--mount",f"type=bind,src={upstream},dst=/data,readonly",CLIENT,"python3","-m","http.server","8080","--directory","/data"],check=True,stdout=subprocess.DEVNULL)
            fixture_started=True
            for attempt in range(30):
                try:
                    client("curl","--fail","--silent","--max-time","5","--output","/dev/null",f"http://{fixture}:8080/ruby/specs.4.8.gz");break
                except AssertionError:
                    if attempt==29:raise
                    time.sleep(1)
            test.request("/service/rest/v1/security/ssrf-protection","PUT",changed)
            client("getent","hosts",fixture)
            ruby_proxy=create("rubygems","proxy","p",remote=f"http://{fixture}:8080/ruby/")
            ruby_group=create("rubygems","group","g",members=[ruby_a,ruby_b,ruby_proxy])
            # Core local credentials are URL-encoded only inside the private fixture.
            from urllib.parse import quote
            credentials="admin:"+quote(test.password,safe="")+"@"
            def ruby_source(repository):return f"http://{credentials}{args.container}:8081/repository/{repository}"
            for label,repository,package in [("hosted",ruby_a,child),("proxy",ruby_proxy,app),("group",ruby_group,app)]:
                print("RubyGems native install:",label,repository,flush=True)
                if label!="proxy":
                    _,info=test.request(f"/repository/{repository}/info/{package}");print(info.decode(),flush=True)
                client("gem","install",package,"--version","1.0.0","--clear-sources","--source",ruby_source(repository),"--install-dir",f"/work/install-{label}","--no-document")
                assert (work/f"install-{label}/gems/{package}-1.0.0").is_dir()
            bundle=work/"bundle";bundle.mkdir();(bundle/"Gemfile").write_text(f"source '{ruby_source(ruby_group)}'\ngem '{app}', '=1.0.0'\n")
            client("sh","-ec","cd /work/bundle; BUNDLE_USER_CONFIG=/work/bundle-config BUNDLE_USER_CACHE=/work/bundle-cache BUNDLE_PATH=/work/bundle-installed bundle install")
            # Real API key issuance/authentication/revocation, enabled only here.
            _,raw=test.request("/service/rest/v1/security/realms/active");realms=json.loads(raw)
            if "RubygemsToken" not in realms:test.request("/service/rest/v1/security/realms/active","PUT",json.dumps(realms+["RubygemsToken"]).encode(),content_type="application/json")
            _,token=test.request(f"/repository/{ruby_a}/api/v1/api_key")
            assert token.startswith(b"RubygemsToken.")
            auth_file.write_text("GEM_HOST_API_KEY="+token.decode()+"\n")
            client("gem","push",f"/work/{child}/{child}-1.0.0.gem","--host",api_a)
            test.request(f"/repository/{ruby_a}/api/v1/api_key","DELETE")
            try:
                request=urllib.request.Request(args.url+f"/repository/{ruby_a}/gems/{child}-1.0.0.gem",headers={"Authorization":token.decode()})
                urllib.request.urlopen(request,timeout=10)
                raise AssertionError("Revoked gem key was accepted")
            except urllib.error.HTTPError as error:assert error.code in (401,403)
            auth_file.write_text("GEM_HOST_API_KEY=Basic "+test.basic+"\n")
            # Build a real noarch RPM, then install it through Nexus using DNF.
            rpmname="nexus-proof-"+test.suffix;rpmwork=work/"rpmbuild"
            for directory in ("BUILD","BUILDROOT","RPMS","SOURCES","SPECS","SRPMS"): (rpmwork/directory).mkdir(parents=True)
            (rpmwork/"SPECS/proof.spec").write_text(f"Name: {rpmname}\nVersion: 1.0\nRelease: 1\nSummary: Nexus native DNF acceptance\nLicense: MIT\nBuildArch: noarch\n%description\nNexus native protocol proof\n%install\nmkdir -p %{{buildroot}}/usr/share/nexus-proof\nprintf 'rpm-acceptance\\n' > %{{buildroot}}/usr/share/nexus-proof/proof.txt\n%files\n/usr/share/nexus-proof/proof.txt\n")
            client("rpmbuild","--define","_topdir /work/rpmbuild","-bb","/work/rpmbuild/SPECS/proof.spec")
            rpm=next((rpmwork/"RPMS/noarch").glob("*.rpm"));rpm_sha=hashlib.sha256(rpm.read_bytes()).hexdigest()
            yum_hosted=create("yum","hosted","h")
            test.request(f"/repository/{yum_hosted}/Packages/{rpm.name}","PUT",rpm.read_bytes())
            expect_rejected(f"/repository/{yum_hosted}/Packages/invalid.rpm","PUT",b"not-an-rpm")
            expect_rejected(f"/repository/{yum_hosted}/Packages/{rpm.name}","PUT",rpm.read_bytes(),{"X-Checksum-Sha256":"0"*64})
            # Duplicate the independent native repo via createrepo-compatible XML
            # obtained from actual hosted Core; proxy preserves validators/blobs.
            yumup=upstream/"yum";(yumup/"repodata").mkdir(parents=True);(yumup/"Packages").mkdir();shutil.copyfile(rpm,yumup/"Packages"/rpm.name)
            _,repomd=test.request(f"/repository/{yum_hosted}/repodata/repomd.xml");(yumup/"repodata/repomd.xml").write_bytes(repomd)
            for location in ET.fromstring(repomd).findall(".//{*}location"):
                href=location.attrib["href"];_,content=test.request(f"/repository/{yum_hosted}/{href}");(yumup/href).write_bytes(content)
            yum_proxy=create("yum","proxy","p",remote=f"http://{fixture}:8080/yum/")
            yum_group=create("yum","group","g",members=[yum_hosted,yum_proxy])
            for label,repository in [("hosted",yum_hosted),("proxy",yum_proxy),("group",yum_group)]:
                repos=work/("repos-"+label);repos.mkdir();(repos/"proof.repo").write_text(f"[nexus-proof]\nname=Nexus proof\nbaseurl=http://{args.container}:8081/repository/{repository}/\nenabled=1\ngpgcheck=0\nrepo_gpgcheck=0\nusername=admin\npassword={test.password}\n")
                client("sh","-ec",f"dnf -y --installroot /tmp/dnf-root --releasever 13 --setopt reposdir=/work/repos-{label} --setopt install_weak_deps=False --disablerepo=\"*\" --enablerepo=nexus-proof install {rpmname}; test \"$(cat /tmp/dnf-root/usr/share/nexus-proof/proof.txt)\" = rpm-acceptance; cp /tmp/dnf-root/usr/share/nexus-proof/proof.txt /work/dnf-{label}-proof.txt")
                assert (work/f"dnf-{label}-proof.txt").read_text()=="rpm-acceptance\n"
                _,downloaded=test.request(f"/repository/{repository}/Packages/{rpm.name}");assert hashlib.sha256(downloaded).hexdigest()==rpm_sha
            # Cached proxy downloads remain available after a real upstream stop.
            subprocess.run(["docker","stop",fixture],check=True,stdout=subprocess.DEVNULL)
            for repository,path,expected in [(ruby_proxy,f"gems/{app}-1.0.0.gem",hashlib.sha256((work/app/f"{app}-1.0.0.gem").read_bytes()).hexdigest()),(yum_proxy,"Packages/"+rpm.name,rpm_sha)]:
                _,content=test.request(f"/repository/{repository}/{path}");assert hashlib.sha256(content).hexdigest()==expected
            image_id=subprocess.check_output(["docker","inspect",args.container,"--format","{{.Image}}"],text=True).strip()
            provenance=json.loads(subprocess.check_output(["docker","exec",args.container,"cat","/opt/nexus/EXTENSIONS-PROVENANCE.json"],text=True))
            report={"image_id":image_id,"application_sha256":provenance["application_sha256"],"ruby_gems":{"native_push":True,"native_install_hosted":True,"proxy_install":True,"group_dependency_merge":True,"bundler_group_install":True,"native_api_key_and_revocation":True,"bad_archive_and_internal_checksum_rejected":True,"sha256_upload_mismatch_rejected":True},"yum":{"real_rpm_build":True,"dnf_hosted_install":True,"dnf_proxy_install":True,"dnf_group_install":True,"artifact_sha256":rpm_sha,"bad_rpm_rejected":True,"sha256_upload_mismatch_rejected":True},"proxy_cache_after_upstream_stop":True,"recipes_tested":6}
            (ROOT/"build/logs/ruby-yum-native.json").write_text(json.dumps(report,indent=2)+"\n");print(json.dumps(report,indent=2))
        finally:
            if fixture_started:subprocess.run(["docker","rm","-f",fixture],check=False,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
            test.request("/service/rest/v1/security/ssrf-protection","PUT",original)
            if not args.keep_repositories:test.cleanup()


if __name__=="__main__":main()
